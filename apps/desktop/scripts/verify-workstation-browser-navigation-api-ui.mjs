import assert from "node:assert/strict";
import { randomUUID } from "node:crypto";
import { writeFileSync } from "node:fs";
import { join } from "node:path";
import { resolveDirectNamespace } from "../../../packages/cli/src/lib/direct-namespace/resolveDirectNamespace.ts";
import { agentUiDriver } from "./verify-workstation-agent-ui-driver.mjs";

export async function verifyWorkstationBrowserNavigationApiUi(options, { scope, url, marker, readProof, guestRead, readView, workspace, terminalTab }) {
	const { until } = agentUiDriver(options);
	const controls = options.controls.forNamespace?.(scope.d.namespaceId) ?? options.controls;
	const report = { source: process.env.GITHUB_SHA, mode: "Actual protected mutation over the owned backend Unix endpoint and current Electron peer; no navigation CLI claim", calls: [] };
	const save = () => writeFileSync(join(options.output, "browser-navigation-api.json"), JSON.stringify(report, null, 2) + "\n");
	await until(async () => (await resolveDirectNamespace(controls.browserNamespaceHome())).description.capabilities.workstationBrowserNavigationV1 === true, "durable browser navigation peer ready");
	const pane = workspace(await readView()).panes.find(row => row.kind === "browser");
	assert.ok(pane);
	const browserTab = workspace(await readView()).activePaneTabId;
	const target = new URL(url); target.pathname = "/owned-navigation"; target.search = "?request=" + randomUUID(); target.hash = "section";
	const input = { operationId: randomUUID(), workspaceId: scope.w.workspaceId, paneId: pane.paneId, url: target.href };
	const request = async (procedure, value) => { const result = await controls.browserNavigationRequest(procedure, value); report.calls.push({ procedure, input: value, ...result }); save(); return result; };
	const first = await request("direct.browserNavigateV1", input);
	assert.equal(first.status, 200); assert.equal(first.result.status, "completed"); assert.deepEqual(first.result.result, { ok: true });
	await until(async () => (await guestRead("location.pathname")) === target.pathname, "real browser navigation rendered");
	const canonical = await until(async () => { const current = workspace(await readView()).panes.find(row => row.paneId === pane.paneId)?.browser?.url; return current === target.href ? current : null; }, "navigation state persisted");
	assert.equal(canonical, target.href);
	const count = async () => (await readProof()).requests.filter(path => path === target.pathname + target.search).length;
	assert.equal(await count(), 1);
	const duplicate = await request("direct.browserNavigateV1", input);
	assert.deepEqual(duplicate.result, first.result); assert.equal(await count(), 1);
	const conflict = await request("direct.browserNavigateV1", { ...input, url });
	assert.equal(conflict.status, 409); assert.equal(await guestRead("location.pathname"), target.pathname);
	const other = await request("direct.browserNavigateV1", { ...input, operationId: randomUUID(), workspaceId: randomUUID() });
	assert.equal(other.status, 400); assert.equal(await guestRead("location.pathname"), target.pathname);
	const state = await request("direct.operationStatus", { operationId: input.operationId });
	assert.deepEqual(state.result, first.result);
	await options.click(`[data-workstation-pane-tabs] [data-tab-id="${terminalTab}"]`);
	await until(async () => workspace(await readView()).activePaneTabId === terminalTab, "terminal stays foreground for background navigation");
	await options.screenshot("browser-navigation-terminal-before");
	const focus = () => options.getPage().evaluate("({tag:document.activeElement?.tagName,className:document.activeElement?.className})");
	await until(async()=>{const current=await focus();return current.tag==="TEXTAREA"&&typeof current.className==="string"&&current.className.includes("xterm-helper-textarea");},"terminal input focus settled before background browser operation");
    const focusBefore = await focus();
	const hidden = { ...input, operationId: randomUUID(), url: new URL("/owned-hidden?request=" + randomUUID(), url).href };
	const hiddenResult = await request("direct.browserNavigateV1", hidden);
	assert.equal(hiddenResult.status, 200); assert.equal(hiddenResult.result.status, "completed");
	assert.equal(workspace(await readView()).activePaneTabId, terminalTab);
	await options.screenshot("browser-navigation-background-terminal");
	assert.deepEqual(await focus(), focusBefore, "background navigation preserves current keyboard focus");
	await options.click(`[data-workstation-pane-tabs] [data-tab-id="${browserTab}"]`);
	await until(async () => (await guestRead("location.pathname")) === "/owned-hidden", "background navigation reached the actual guest");
	const restored = await request("direct.browserNavigateV1", { ...input, operationId: randomUUID(), url });
	assert.equal(restored.status, 200);
	await until(async () => (await guestRead("document.body.innerText"))?.includes(marker), "original owned page restored after navigation API checks");
	report.completed = { first: first.result, hidden: hiddenResult.result, canonical, oneRequestForRepeatedId: true, backgroundTabUnchanged: true }; save();
	return { report, async afterReopen() {
		await until(async () => (await resolveDirectNamespace(controls.browserNamespaceHome())).description.capabilities.workstationBrowserNavigationV1 === true, "reopened navigation peer ready");
		const before = await guestRead("location.href");
		const persisted = await request("direct.operationStatus", { operationId: input.operationId });
		assert.deepEqual(persisted.result, first.result);
		const repeated = await request("direct.browserNavigateV1", input);
		assert.deepEqual(repeated.result, first.result);
		assert.equal(await guestRead("location.href"), before); assert.equal(await count(), 1);
		report.reopened = { persisted: persisted.result, noReplayOrRetarget: true }; save();
	} };
}
