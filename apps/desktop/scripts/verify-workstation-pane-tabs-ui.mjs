import assert from "node:assert/strict";
import {writeFileSync} from "node:fs";
import {join} from "node:path";
import {agentUiDriver} from "./verify-workstation-agent-ui-driver.mjs";
export async function verifyWorkstationPaneTabsUi({getPage,click,screenshot,output,controls,closeReopen,nativeDrag}) {
 const {evaluate,until}=agentUiDriver({getPage,click,screenshot,output});
 const active=()=>evaluate(`(async()=>{const {snapshot}=await window.directWorkstation.getWorkspaceView();const target=snapshot.targets.find(t=>t.connectionId===snapshot.activeConnectionId);return target.workspaces.find(w=>w.tabId===target.activeTabId);})()`);
 const root='[data-workstation-pane-tabs]';
 const before=await active();assert.equal(before.panes.length,3);
 const original=await Promise.all(before.panes.map(p=>controls.inspectPresetTerminal(p.resourceId)));
 await screenshot('pane-tabs-original-workspace-before-new-terminal');
 await click('text:New terminal');
 const after=await until(async()=>{const w=await active();return w.panes.length===before.panes.length+1&&w;},'new terminal resource saved');
 await screenshot('pane-tabs-new-terminal-opens-separate-original-tab');
 assert.equal(after.paneTabs?.length,2,'New terminal preserves the existing layout and opens a separate terminal tab');
 assert.deepEqual(after.paneTabs[0].layout,before.paneTabs?.[0]?.layout??before.layout);
 const newTab=after.paneTabs[1].tabId;assert.equal(after.activePaneTabId,newTab);
 await until(()=>evaluate(`document.querySelectorAll('${root} [data-tab-id]').length===2`),'original nested tab bar');
 await click('text:Split vertically');
 const split=await until(async()=>{const w=await active();return w.panes.length===5&&w;},'split in current terminal tab');
 assert.equal(split.paneTabs.length,2);assert.equal(split.paneTabs[1].layout.type,'split');assert.equal(split.paneTabs[1].layout.axis,'vertical');
 assert.deepEqual(split.paneTabs[0].layout,after.paneTabs[0].layout);
 await screenshot('pane-tabs-split-contained-in-selected-tab');
 const titleSelector=`${root} [data-tab-id="${newTab}"] .text-left`;
 const point=await evaluate(`(()=>{const r=document.querySelector(${JSON.stringify(titleSelector)}).getBoundingClientRect();return {x:r.x+r.width/2,y:r.y+r.height/2};})()`);
 for(const type of ['mousePressed','mouseReleased'])await getPage().call('Input.dispatchMouseEvent',{type,...point,button:'left',clickCount:2});
 await until(()=>evaluate(`Boolean(document.querySelector('${root} [data-tab-id="${newTab}"] input'))`),'original tab rename input');
 await getPage().call('Input.insertText',{text:'SSH tools 中文'});
 for(const type of ['keyDown','keyUp'])await getPage().call('Input.dispatchKeyEvent',{type,key:'Enter',code:'Enter',windowsVirtualKeyCode:13});
 await until(async()=>{const w=await active();return w.paneTabs.find(t=>t.tabId===newTab)?.label==='SSH tools 中文';},'renamed terminal tab persisted');
 await screenshot('pane-tabs-original-rename');
 assert.equal(typeof nativeDrag,'function');
 const points=await evaluate(`(()=>{const a=document.querySelector('${root} [data-tab-id="${newTab}"]').getBoundingClientRect(),b=document.querySelector('${root} [data-tab-id="${after.paneTabs[0].tabId}"]').getBoundingClientRect();const y=a.y+a.height/2;return [{x:a.x+a.width/2,y},{x:a.x+a.width/2-48,y},{x:b.x+10,y},{x:b.x+20,y},{x:b.x+8,y}];})()`);
 const drag=await nativeDrag(points);writeFileSync(join(output,'pane-tabs-native-drag.json'),JSON.stringify(drag,null,2)+'\n');
 await until(async()=>{const w=await active();return w.paneTabs[0].tabId===newTab;},'original tab drag order persisted');
 await screenshot('pane-tabs-original-reordered');
 const saved=await active();await closeReopen();
 await until(async()=>{const w=await active();return w?.paneTabs?.length===2&&w.panes.length===5&&w;},'nested tabs restored');
 const reopened=await active();assert.deepEqual(reopened.paneTabs,saved.paneTabs);assert.equal(reopened.activePaneTabId,saved.activePaneTabId);
 for(let i=0;i<original.length;i++)assert.equal((await controls.inspectPresetTerminal(before.panes[i].resourceId)).pid,original[i].pid);
 await screenshot('pane-tabs-reopen-keeps-layouts-and-executions');
 await click(`${root} [data-tab-id="${newTab}"] button[aria-label="Close tab"]`);
 const closed=await until(async()=>{const w=await active();return w.paneTabs.length===1&&w;},'close original terminal tab');
 assert.deepEqual(closed.panes,before.panes);assert.equal(closed.paneTabs[0].tabId,after.paneTabs[0].tabId);
 await screenshot('pane-tabs-close-preserves-other-group');
 writeFileSync(join(output,'pane-tabs-acceptance.json'),JSON.stringify({before,after,split,saved,reopened,closed,originalPids:original.map(p=>p.pid),errors:getPage().errors},null,2)+'\n');
 assert.deepEqual(getPage().errors,[]);
}
